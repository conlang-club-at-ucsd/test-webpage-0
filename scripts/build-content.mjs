// converts projects/raw-md-files/**/*.md into static json + html the site can use

import { readdir, readFile, writeFile, mkdir, rm } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseMarkdown, slugify, stripHtml } from './md.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'projects', 'raw-md-files');
const OUT = path.join(ROOT, 'projects', 'data');
const PROJECTS = path.join(ROOT, 'projects');

const RESERVED = new Set(['data', 'raw-md-files']);

// collect .md files recursive, ignores a bunch of junk files from my os
async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const e of entries) {
    if (e.name.startsWith('.')) continue;
    const full = path.join(dir, e.name);
    if (e.isDirectory()) files.push(...(await walk(full)));
    else if (e.name.toLowerCase().endsWith('.md')) files.push(full);
  }
  return files;
}

// [name]/index.md -> "[name]"
function slugFor(file) {
  const rel = path.relative(SRC, file).replace(/\.md$/i, '');
  const parts = rel.split(path.sep);
  if (parts[parts.length - 1].toLowerCase() === 'index') parts.pop();
  return slugify(parts.join('-')) || 'index-page';
}

const escapeAttr = (s) =>
  String(s ?? '')
    .replace(/&/g, '&amp;')
    .replace(/"/g, '&quot;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');

function renderToc(headings) {
  const items = headings.filter((h) => h.level >= 2 && h.level <= 3);
  if (items.length === 0) return '';
  const links = items
    .map(
      (h) =>
        `        <li class="toc--l${h.level}"><a href="#${escapeAttr(h.id)}">${escapeAttr(h.text)}</a></li>`
    )
    .join('\n');
  return `      <aside class="doc-toc" aria-label="On this page">
        <p class="doc-toc__title">On this page</p>
        <ul>
${links}
        </ul>
      </aside>`;
}


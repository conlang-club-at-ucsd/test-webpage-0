async function removeStalePages(validSlugs) {
  let entries = [];
  try {
    entries = await readdir(PROJECTS, { withFileTypes: true });
  } catch {
    return;
  }
  for (const e of entries) {
    if (!e.isDirectory()) continue;
    if (RESERVED.has(e.name)) continue;
    if (validSlugs.has(e.name)) continue;
    const indexFile = path.join(PROJECTS, e.name, 'index.html');
    let content = '';
    try {
      content = await readFile(indexFile, 'utf8');
    } catch {
      continue;
    }
    if (content.includes('generated by scripts/build-content.mjs')) {
      await rm(path.join(PROJECTS, e.name), { recursive: true, force: true });
      console.log(`  removed stale projects/${e.name}/`);
    }
  }
}

async function main() {
  const files = (await walk(SRC)).sort();
  await rm(OUT, { recursive: true, force: true });
  await mkdir(OUT, { recursive: true });

  const manifest = [];
  const seen = new Set();

  for (const file of files) {
    const slug = slugFor(file);
    if (RESERVED.has(slug)) {
      throw new Error(`Slug "${slug}" from ${path.relative(ROOT, file)} collides with reserved projects/${slug}/`);
    }
    if (seen.has(slug)) throw new Error(`Duplicate slug "${slug}" from ${path.relative(ROOT, file)}`);
    seen.add(slug);

    const raw = await readFile(file, 'utf8');
    const doc = parseMarkdown(raw);
    const title = doc.frontmatter.title || doc.title || slug;
    const description =
      doc.frontmatter.description || doc.frontmatter.excerpt || doc.excerpt || stripHtml(doc.html).slice(0, 240);
    const source = path.relative(ROOT, file).split(path.sep).join('/');
    const author = doc.frontmatter.author || doc.frontmatter.by || '';
    const entry = {
      slug,
      title,
      ...(author ? { author: String(author) } : {}),
      excerpt: description.slice(0, 240),
      source,
      url: `/projects/data/${slug}.json`,
      page: `/projects/${slug}/`,
    };

    await writeFile(path.join(OUT, `${slug}.json`), JSON.stringify({ ...entry, ...doc }, null, 2) + '\n');

    const html = renderPage({ slug, title, description: entry.excerpt, doc, source });
    const dir = path.join(PROJECTS, slug);
    await mkdir(dir, { recursive: true });
    await writeFile(path.join(dir, 'index.html'), html);

    manifest.push(entry);
    console.log(`  ${entry.source} -> projects/data/${slug}.json + projects/${slug}/index.html`);
  }

  await removeStalePages(seen);

  await writeFile(path.join(OUT, 'index.json'), JSON.stringify({ projects: manifest }, null, 2) + '\n');
  console.log(`Built ${manifest.length} page(s) + index.json + ${manifest.length} html page(s)`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
